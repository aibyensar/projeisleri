import { LibreDwg, Dwg_File_Type } from '@mlightcad/libredwg-web';
import fs from 'fs';
const lib = await LibreDwg.create('./node_modules/@mlightcad/libredwg-web/wasm/');
const buf = fs.readFileSync(process.argv[2]);
const dwg = lib.dwg_read_data(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength), Dwg_File_Type.DWG);
const db = lib.convert(dwg);
fs.writeFileSync(process.argv[3], JSON.stringify(db, (k, v) => typeof v === 'bigint' ? Number(v) : v));
console.log(Object.keys(db), db.entities?.length);
const c = {}; for (const e of db.entities) c[e.type] = (c[e.type] || 0) + 1; console.log(c);
console.log('bloklar', db.tables?.BLOCK_RECORD?.entries?.length);
